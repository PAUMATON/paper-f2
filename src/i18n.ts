export const STRINGS: Record<Lang, Strings> = { ca, es, en };

export function detectLang(): Lang {
  const code = (navigator.language || "").toLowerCase();
  if (code.startsWith("es")) return "es";
  if (code.startsWith("en")) return "en";
  return "ca";
}
